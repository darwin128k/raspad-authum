#!/usr/bin/env python3
"""Generate the entity-class trampolines for the game-library layer.

The engine looks an entity's spawn function up *in the game module* — the
library it loaded as the game. When that module is Authum (we stand in for
the game), the class names (`info_player_start`, `func_breakable`, …) have to
be exported by us, each forwarding to the real game.

The list is the game library's own plain C exports; this script reads them
off a game library and writes the C file.

    tools/gen-game-classes.py <game.so|game.dll> > src/authum/gamedll/game_classes.cpp

Names we implement ourselves are skipped — the engine finds those in
Authum already.
"""

import re
import subprocess
import sys

# Ours: the engine looks these up in the game module and we serve them.
SKIP = {
    "GiveFnptrsToDll",
    "GetEntityAPI",
    "GetEntityAPI2",
    "GetNewDLLFunctions",
    "worldspawn",
    "DispatchSpawn",
    "GameDLLInit",
    "Server_GetBlendingInterface",
    "authum_engine_funcs",
    "authum_globals",
}

PLAIN = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
# Entity classes in the HL1 SDK are all lower case (`info_player_start`,
# `func_breakable`, …); the SDK's helper exports are CamelCase (`PM_*`,
# `AngleBetweenVectors`, …) and the engine never looks those up.
CLASS = re.compile(r"^[a-z][a-z0-9_]*$")


def exports(path: str) -> list[str]:
    """Plain (unmangled) exported function names of a shared library."""
    names: set[str] = set()
    try:
        out = subprocess.run(
            ["nm", "-D", "--defined-only", path],
            capture_output=True, text=True, check=True).stdout
        for line in out.splitlines():
            parts = line.split()
            if len(parts) >= 3 and parts[1] in ("T", "W", "t", "i"):
                name = parts[2]
                if PLAIN.match(name):
                    names.add(name)
    except (OSError, subprocess.CalledProcessError):
        pass
    try:
        out = subprocess.run(
            ["objdump", "-p", path],
            capture_output=True, text=True, check=True).stdout
        in_table = False
        for line in out.splitlines():
            if "Export Address Table" in line or "Export RVA" in line:
                in_table = True
                continue
            if in_table:
                m = re.search(r"\s+\[\s*\d+\]\s+[0-9A-Fa-f]+\s+(\S+)", line)
                if m:
                    name = m.group(1)
                    if PLAIN.match(name):
                        names.add(name)
                elif line.strip() == "":
                    in_table = False
    except (OSError, subprocess.CalledProcessError):
        pass
    return sorted(n for n in names if n not in SKIP and CLASS.match(n))


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    names = exports(sys.argv[1])
    if not names:
        print("no plain exports found in %s" % sys.argv[1], file=sys.stderr)
        return 1
    out = sys.stdout
    out.write("""/*
 * Entity-class trampolines — generated by tools/gen-game-classes.py, do not edit.
 *
 * The engine resolves an entity's spawn function by its class name in the
 * game module. We are that module now, so every class name the real game
 * exports has to be exported by us too — each one forwards to the game.
 */

#include <authum/gamedll/game.h>

#include <authum/export.h>
#include <authum/ptr.h>
#include <authum/char.h>
#include <authum/null.h>
#include <lh/cast/reinterpret.h>

#include <extdll.h>

/* The engine looks these up by name: they must be exported. */
#define AUTHUM_CLASS extern "C" AUTHUM_IMAGE_EXPORT

namespace
{
authum_ptr
class_symbol(const authum_char_t *name)
{
    return authum_gamedll::gamedll_symbol(name);
}
} // namespace

""")
    for name in names:
        out.write("AUTHUM_CLASS void\n%s(entvars_t *pev)\n{\n"
                  "    typedef void (*fn_t)(entvars_t *);\n"
                  "    fn_t fn = lh_cast_reinterpret(fn_t, class_symbol(\"%s\"));\n"
                  "    if (!authum_null_eq(fn))\n"
                  "    {\n"
                  "        fn(pev);\n"
                  "    }\n"
                  "}\n\n" % (name, name))
    out.write("/* %d class trampolines. */\n" % len(names))
    return 0


if __name__ == "__main__":
    sys.exit(main())
